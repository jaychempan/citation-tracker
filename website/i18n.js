let currentLang = navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
try {
  const savedLang = localStorage.getItem('lang');
  if (savedLang === 'zh' || savedLang === 'en') currentLang = savedLang;
} catch (_error) { /* The page still works when browser storage is disabled. */ }

function applyLang(lang) {
  const dict = lang === 'en' ? EN : ZH;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.innerHTML = dict[key];
  });
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria-label');
    if (dict[key]) el.setAttribute('aria-label', dict[key]);
  });
  const languageButton = document.querySelector('.lang-toggle');
  if (languageButton) {
    languageButton.textContent = lang === 'en' ? '中文' : 'EN';
    languageButton.setAttribute('aria-label', lang === 'en' ? '切换为中文' : 'Switch to English');
  }
  document.title = document.querySelector('.policy') ? `${dict.privacy_title} - Citation Tracker` : dict.meta_title;
  document.querySelector('meta[name="description"]')?.setAttribute('content', dict.meta_description);
  try { localStorage.setItem('lang', lang); } catch (_error) { /* Optional preference. */ }
  currentLang = lang;
  document.dispatchEvent(new CustomEvent('citation-language-change', { detail: { lang } }));
}

function toggleLang() {
  applyLang(currentLang === 'zh' ? 'en' : 'zh');
}

function toggleNav() {
  const navLinks = document.querySelector('.nav-links');
  const navToggle = document.querySelector('.nav-toggle');
  if (!navLinks || !navToggle) return;
  const isOpen = navLinks.classList.toggle('open');
  navToggle.classList.toggle('active', isOpen);
  navToggle.setAttribute('aria-expanded', String(isOpen));
}

// Close mobile nav on link click
document.addEventListener('click', (e) => {
  const navLinks = document.querySelector('.nav-links');
  const navToggle = document.querySelector('.nav-toggle');
  if (!navLinks || !navToggle) return;
  if (navLinks.classList.contains('open') && (e.target.closest('.nav-links a') || (!navLinks.contains(e.target) && !navToggle.contains(e.target)))) {
    navLinks.classList.remove('open');
    navToggle.classList.remove('active');
    navToggle.setAttribute('aria-expanded', 'false');
  }
});

